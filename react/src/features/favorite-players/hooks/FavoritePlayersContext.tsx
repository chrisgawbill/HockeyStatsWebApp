import {
  createContext,
  ReactNode,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';
import { getServiceWorkerContainer } from '@/lib/serviceWorker';
import { ApiError } from '@/lib/apiClient';
import { useAuth } from '@/lib/auth/AuthContext';
import {
  addFavoritePlayer,
  fetchFavoritePlayers,
  fetchWeeklyReportPush,
  fetchWeeklyReports,
  markWeeklyReportRead,
  removeFavoritePlayer,
  setWeeklyReportPush,
  updateFavoritePlayerCategory,
} from '@/features/favorite-players/api/favoritePlayersApi';
import {
  DEFAULT_FAN_TIER,
  type FavoriteCategory,
} from '@/lib/favoriteCategory';
import type {
  FavoritePlayer,
  WeeklyPlayerReport,
} from '@/features/favorite-players/types/favoritePlayers';

/** Reports arrive weekly; refreshing on focus plus this cadence is plenty. */
const POLL_INTERVAL_MS = 15 * 60 * 1000;
const FOCUS_REFRESH_MIN_MS = 60 * 1000;

/** Thrown by `toggleFavorite` when the API refused an 11th favorite. */
export class FavoriteLimitError extends Error {
  constructor() {
    super('Favorite player limit reached');
    this.name = 'FavoriteLimitError';
  }
}

export interface FavoritePlayersState {
  isSignedIn: boolean;
  /**
   * False once the API answered that favorite players do not exist (404, an
   * API deploy older than API-WPR-01); stars then hide instead of failing.
   */
  available: boolean;
  favorites: FavoritePlayer[];
  reports: WeeklyPlayerReport[];
  unreadCount: number;
  isFavorite: (playerId: number) => boolean;
  /** Rejects (FavoriteLimitError on the cap) after restoring the old list. */
  toggleFavorite: (playerId: number, name: string) => Promise<void>;
  /** Rejects after restoring the previous favorites when the save fails. */
  updatePlayerCategory: (
    playerId: number,
    category: FavoriteCategory,
  ) => Promise<void>;
  markReportRead: (weekStart: string) => void;
  markAllReportsRead: () => void;
  /** The Monday push switch; null until loaded. */
  weeklyPush: boolean | null;
  setWeeklyPush: (enabled: boolean) => Promise<void>;
}

const FavoritePlayersContext = createContext<FavoritePlayersState | null>(null);

function withReadFlag(reports: WeeklyPlayerReport[], weekStart: string) {
  return reports.map((report) =>
    report.weekStart === weekStart ? { ...report, read: true } : report,
  );
}

/**
 * Favorite players and the Weekly Player Report inbox for the signed-in user.
 * Reports are generated by the API each Monday; the provider loads them on
 * sign-in, when the tab regains focus, and every 15 minutes while visible.
 */
export function FavoritePlayersProvider({ children }: { children: ReactNode }) {
  const { token } = useAuth();
  const [available, setAvailable] = useState(true);
  const [favorites, setFavorites] = useState<FavoritePlayer[]>([]);
  const [reports, setReports] = useState<WeeklyPlayerReport[]>([]);
  const [weeklyPush, setWeeklyPushState] = useState<boolean | null>(null);
  const lastFetchRef = useRef(0);
  const tokenRef = useRef(token);
  tokenRef.current = token;

  const refreshReports = useCallback(async (activeToken: string) => {
    lastFetchRef.current = Date.now();
    try {
      const inbox = await fetchWeeklyReports(activeToken);
      if (tokenRef.current === activeToken) setReports(inbox.reports);
    } catch (error) {
      console.error('Failed to load Weekly Player Reports:', error);
    }
  }, []);

  useEffect(() => {
    if (!token) {
      setFavorites([]);
      setReports([]);
      setWeeklyPushState(null);
      return;
    }

    let cancelled = false;
    fetchFavoritePlayers(token)
      .then((next) => {
        if (cancelled) return;
        setAvailable(true);
        setFavorites(next);
      })
      .catch((error) => {
        if (cancelled) return;
        if (error instanceof ApiError && error.status === 404) {
          setAvailable(false);
        }
        console.error('Failed to load favorite players:', error);
      });
    fetchWeeklyReportPush(token)
      .then((enabled) => {
        if (!cancelled) setWeeklyPushState(enabled);
      })
      .catch((error) =>
        console.error('Failed to load weekly report setting:', error),
      );
    refreshReports(token);

    const interval = window.setInterval(() => {
      if (document.visibilityState === 'visible') refreshReports(token);
    }, POLL_INTERVAL_MS);
    const onVisible = () => {
      if (
        document.visibilityState === 'visible' &&
        Date.now() - lastFetchRef.current > FOCUS_REFRESH_MIN_MS
      ) {
        refreshReports(token);
      }
    };
    document.addEventListener('visibilitychange', onVisible);

    return () => {
      cancelled = true;
      window.clearInterval(interval);
      document.removeEventListener('visibilitychange', onVisible);
    };
  }, [token, refreshReports]);

  // The service worker tells open tabs when a weekly notification was tapped.
  useEffect(() => {
    const serviceWorker = getServiceWorkerContainer();
    if (!serviceWorker) return;
    const onMessage = (event: MessageEvent) => {
      const data = event.data as { type?: string; weekStart?: unknown } | null;
      if (data?.type === 'wpr-navigate' && typeof data.weekStart === 'string') {
        window.location.hash = `#/weekly-report/${data.weekStart}`;
      } else if (data?.type === 'wpr-report-read' && tokenRef.current) {
        refreshReports(tokenRef.current);
      }
    };
    serviceWorker.addEventListener('message', onMessage);
    return () => serviceWorker.removeEventListener('message', onMessage);
  }, [refreshReports]);

  const isFavorite = useCallback(
    (playerId: number) => favorites.some((f) => f.playerId === playerId),
    [favorites],
  );

  const toggleFavorite = useCallback(
    async (playerId: number, name: string) => {
      if (!token) return;
      const wasFavorite = favorites.some((f) => f.playerId === playerId);
      const previous = favorites;
      setFavorites(
        wasFavorite
          ? favorites.filter((f) => f.playerId !== playerId)
          : [
              ...favorites,
              {
                playerId,
                name,
                teamTriCode: null,
                position: null,
                headshot: null,
                since: new Date().toISOString(),
                tier: DEFAULT_FAN_TIER,
                label: null,
              },
            ],
      );
      try {
        setFavorites(
          wasFavorite
            ? await removeFavoritePlayer(token, playerId)
            : await addFavoritePlayer(token, playerId),
        );
      } catch (error) {
        console.error('Failed to update favorite player:', error);
        setFavorites(previous);
        if (error instanceof ApiError && error.status === 409) {
          throw new FavoriteLimitError();
        }
        throw error;
      }
    },
    [token, favorites],
  );

  const updatePlayerCategory = useCallback(
    async (playerId: number, category: FavoriteCategory) => {
      if (!token) return;
      const previous = favorites;
      setFavorites(
        favorites.map((f) =>
          f.playerId === playerId ? { ...f, ...category } : f,
        ),
      );
      try {
        setFavorites(
          await updateFavoritePlayerCategory(token, playerId, category),
        );
      } catch (error) {
        console.error('Failed to update favorite player category:', error);
        setFavorites(previous);
        throw error;
      }
    },
    [token, favorites],
  );

  const markReportRead = useCallback(
    (weekStart: string) => {
      if (!token) return;
      setReports((current) => withReadFlag(current, weekStart));
      markWeeklyReportRead(token, weekStart).catch((error) =>
        console.error('Failed to mark Weekly Player Report read:', error),
      );
    },
    [token],
  );

  const markAllReportsRead = useCallback(() => {
    if (!token) return;
    const unread = reports.filter((report) => !report.read);
    setReports((current) => current.map((r) => ({ ...r, read: true })));
    for (const report of unread) {
      markWeeklyReportRead(token, report.weekStart).catch((error) =>
        console.error('Failed to mark Weekly Player Report read:', error),
      );
    }
  }, [token, reports]);

  const setWeeklyPush = useCallback(
    async (enabled: boolean) => {
      if (!token) return;
      const previous = weeklyPush;
      setWeeklyPushState(enabled);
      try {
        setWeeklyPushState(await setWeeklyReportPush(token, enabled));
      } catch (error) {
        console.error('Failed to update weekly report setting:', error);
        setWeeklyPushState(previous);
        throw error;
      }
    },
    [token, weeklyPush],
  );

  const value = useMemo<FavoritePlayersState>(
    () => ({
      isSignedIn: token !== null,
      available,
      favorites,
      reports,
      unreadCount: reports.filter((report) => !report.read).length,
      isFavorite,
      toggleFavorite,
      updatePlayerCategory,
      markReportRead,
      markAllReportsRead,
      weeklyPush,
      setWeeklyPush,
    }),
    [
      token,
      available,
      favorites,
      reports,
      isFavorite,
      toggleFavorite,
      updatePlayerCategory,
      markReportRead,
      markAllReportsRead,
      weeklyPush,
      setWeeklyPush,
    ],
  );

  return (
    <FavoritePlayersContext.Provider value={value}>
      {children}
    </FavoritePlayersContext.Provider>
  );
}

export function useFavoritePlayers(): FavoritePlayersState {
  const context = useContext(FavoritePlayersContext);
  if (!context) {
    throw new Error(
      'useFavoritePlayers must be used within a FavoritePlayersProvider',
    );
  }
  return context;
}
